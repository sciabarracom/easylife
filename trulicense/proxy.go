package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"regexp"
	"sort"
	"strings"
)

const (
	// proxyName names every proxy resource: deployment, service, ingress and
	// the configmap holding both the provisioned hosts and the nginx config.
	proxyName  = "trulicense-proxy"
	proxyImage = "docker.io/library/nginx:stable-alpine"
	// traefik is the k3s ingress controller: the proxy sends the requests back
	// to it with the local miniops.me host, so the existing ingresses apply.
	traefikURL = "http://traefik.kube-system.svc.cluster.local:80"
	// s3.<host> goes straight to SeaweedFS keeping its Host, which S3 signs:
	// through traefik it would match *.<host> and loop back to the proxy.
	s3URL = "http://seaweedfs.openserverless.svc.cluster.local:9000"
)

// provisionProxy adds hosts to the ones already provisioned, possibly by
// other licences, and applies the proxy for all of them. Running it again with
// the same hosts changes nothing.
func provisionProxy(k *Kube, hosts []string) error {
	current, err := k.kubectl("", "-n", namespace, "get", "configmap", proxyName,
		"--ignore-not-found", "-o", "jsonpath={.data.hosts}")
	if err != nil {
		return err
	}
	all := mergeHosts(strings.Fields(current), hosts)

	manifest, err := json.Marshal(proxyManifests(all))
	if err != nil {
		return err
	}
	if _, err := k.kubectl(string(manifest), "apply", "-f", "-"); err != nil {
		return fmt.Errorf("provisioning the proxy: %v", err)
	}
	for _, h := range all {
		fmt.Printf("Provisioned http://%s and http://<app>.%s\n", h, h)
	}

	fmt.Println("Waiting for the proxy to be ready...")
	if _, err := k.kubectl("", "-n", namespace, "rollout", "status",
		"deployment/"+proxyName, "--timeout=180s"); err != nil {
		fmt.Printf("WARNING: the proxy is not ready yet: %v\n", err)
	}
	return nil
}

// mergeHosts returns the sorted union of the host lists.
func mergeHosts(lists ...[]string) []string {
	seen := map[string]bool{}
	var all []string
	for _, l := range lists {
		for _, h := range l {
			if !seen[h] {
				seen[h] = true
				all = append(all, h)
			}
		}
	}
	sort.Strings(all)
	return all
}

// nginxConf maps <host> to miniops.me and <app>.<host> to <app>.miniops.me,
// with websockets and bodies up to 1g, except s3.<host> that keeps its Host.
// It is included in nginx's http block.
func nginxConf(hosts []string) string {
	var b strings.Builder
	b.WriteString(`# Generated by trulicense, rewritten at every run.
server_names_hash_bucket_size 128;
client_max_body_size 1g;

map $http_upgrade $connection_upgrade {
    default upgrade;
    ''      close;
}

server {
    listen 80 default_server;
    return 404;
}
`)
	for _, h := range hosts {
		fmt.Fprintf(&b, "\nserver {\n    listen 80;\n    server_name %s;\n%s}\n",
			h, proxyLocation(traefikURL, "miniops.me"))
		// An exact server_name wins over the regex below.
		fmt.Fprintf(&b, "\nserver {\n    listen 80;\n    server_name s3.%s;\n%s}\n",
			h, proxyLocation(s3URL, "$host"))
		fmt.Fprintf(&b, "\nserver {\n    listen 80;\n    server_name ~^(?<app>[a-z0-9-]+)\\.%s$;\n%s}\n",
			regexp.QuoteMeta(h), proxyLocation(traefikURL, "$app.miniops.me"))
	}
	return b.String()
}

func proxyLocation(upstream, host string) string {
	return `    location / {
        proxy_pass ` + upstream + `;
        proxy_http_version 1.1;
        proxy_set_header Host ` + host + `;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade;
        proxy_set_header X-Forwarded-Host $host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_request_buffering off;
        proxy_buffering off;
        proxy_read_timeout 600s;
        proxy_send_timeout 600s;
    }
`
}

type obj = map[string]any

// proxyManifests returns the proxy resources as a List for `kubectl apply`.
func proxyManifests(hosts []string) obj {
	conf := nginxConf(hosts)
	sum := sha256.Sum256([]byte(conf))
	labels := obj{"app.kubernetes.io/name": proxyName}
	meta := obj{"name": proxyName, "namespace": namespace, "labels": labels}

	configMap := obj{
		"apiVersion": "v1", "kind": "ConfigMap", "metadata": meta,
		"data": obj{"hosts": strings.Join(hosts, "\n"), "default.conf": conf},
	}

	deployment := obj{
		"apiVersion": "apps/v1", "kind": "Deployment", "metadata": meta,
		"spec": obj{
			"replicas": 1,
			"selector": obj{"matchLabels": labels},
			"template": obj{
				"metadata": obj{
					"labels": labels,
					// A new config rolls the pod, so nginx reloads it.
					"annotations": obj{"trulicense/config-sha256": hex.EncodeToString(sum[:])},
				},
				"spec": obj{
					"containers": []obj{{
						"name":            "nginx",
						"image":           proxyImage,
						"imagePullPolicy": "IfNotPresent",
						"ports":           []obj{{"name": "http", "containerPort": 80}},
						"readinessProbe":  obj{"tcpSocket": obj{"port": 80}},
						"resources": obj{
							"requests": obj{"cpu": "10m", "memory": "16Mi"},
							"limits":   obj{"memory": "128Mi"},
						},
						"volumeMounts": []obj{{
							"name": "conf", "mountPath": "/etc/nginx/conf.d/default.conf", "subPath": "default.conf",
						}},
					}},
					"volumes": []obj{{
						"name":      "conf",
						"configMap": obj{"name": proxyName, "items": []obj{{"key": "default.conf", "path": "default.conf"}}},
					}},
				},
			},
		},
	}

	service := obj{
		"apiVersion": "v1", "kind": "Service", "metadata": meta,
		"spec": obj{
			"selector": labels,
			"ports":    []obj{{"name": "http", "port": 80, "targetPort": "http"}},
		},
	}

	backend := obj{"service": obj{"name": proxyName, "port": obj{"number": 80}}}
	var rules []obj
	for _, h := range hosts {
		for _, host := range []string{h, "*." + h} {
			rules = append(rules, obj{
				"host": host,
				"http": obj{"paths": []obj{{"path": "/", "pathType": "Prefix", "backend": backend}}},
			})
		}
	}
	ingress := obj{
		"apiVersion": "networking.k8s.io/v1", "kind": "Ingress",
		"metadata": obj{
			"name": proxyName, "namespace": namespace, "labels": labels,
			"annotations": obj{
				"traefik.ingress.kubernetes.io/transport.respondingTimeouts.idleTimeout":  "600",
				"traefik.ingress.kubernetes.io/transport.respondingTimeouts.readTimeout":  "600",
				"traefik.ingress.kubernetes.io/transport.respondingTimeouts.writeTimeout": "600",
			},
		},
		"spec": obj{"ingressClassName": "traefik", "rules": rules},
	}

	return obj{"apiVersion": "v1", "kind": "List", "items": []obj{configMap, deployment, service, ingress}}
}
